package gf16

import "github.com/klauspost/cpuid/v2"

//go:generate go run asmgen/x86.go

// The amd64 backend is a port of ParPar's x86 methods to Go assembly:
//
//   - Shuffle (SSSE3) and Shuffle (AVX2): the 4-bit nibble PSHUFB split-table
//     kernel (gf16_shuffle_x86.h). Always registered when the CPU has the
//     instruction set.
//   - Affine2x (GFNI+AVX2) and Affine2x (GFNI+AVX512): GF2P8AFFINEQB based
//     kernels (gf16_affine2x_x86.h); see affine_amd64.go. Registered only on CPUs
//     with GFNI and the matching AVX/AVX-512 support, and preferred over Shuffle.
//
// The assembly lives in shuffle_amd64.s and affine_amd64.s, generated by
// asmgen/x86.go.

// Prepared layout of the shuffle kernels (ParPar's): a block is two vectors;
// the first holds the high bytes of the block's words, the second the low
// bytes, and within a 128-bit lane the vectors cover 8 words each.
const (
	shuffleStrideSSSE3 = 32
	shuffleStrideAVX2  = 64
)

// shufTable holds the PSHUFB tables for one coefficient: for each nibble
// position k of a word (bits 4k..4k+3) a 16-byte table of the low byte and one
// of the high byte of coeff*(nibble<<4k), in the order low0 high0 low1 high1
// low2 high2 low3 high3. The assembly builds it (shufSetup*); internal/gfmodel
// has the slow Go model the tests compare it with.
type shufTable [128]byte

// Table builders (shuffle_amd64.s): set every byte of *t for coefficient c.
// Only tests call them; the kernels above run the same code inline.

//go:noescape
func shufSetupSSSE3(t *shufTable, c uint16)

//go:noescape
func shufSetupAVX2(t *shufTable, c uint16)

// Kernel entry points (shuffle_amd64.s). n is a non-zero multiple of the
// kernel stride. Mul writes dst; MulAdd xors into it. They match the
// kernel.mul / kernel.mulAdd signatures and build the tables for coeff
// themselves, so they are registered directly.

//go:noescape
func shufMulSSSE3(dst, src *byte, n int, coeff uint16)

//go:noescape
func shufMulAddSSSE3(dst, src *byte, n int, coeff uint16)

//go:noescape
func shufMulAVX2(dst, src *byte, n int, coeff uint16)

//go:noescape
func shufMulAddAVX2(dst, src *byte, n int, coeff uint16)

//go:noescape
func shufPrepareSSSE3(dst, src *byte, n int)

//go:noescape
func shufFinishSSSE3(dst, src *byte, n int)

//go:noescape
func shufPrepareAVX2(dst, src *byte, n int)

//go:noescape
func shufFinishAVX2(dst, src *byte, n int)

//go:noescape
func xorSSE(dst, src *byte, n int)

//go:noescape
func xorAVX2(dst, src *byte, n int)

// ParPar's shuffle kernels have no multi-region form (their tables fill the
// register file), so a multi call is one single-source pass per region, as in
// ParPar's gf16_muladd loops. The passes run inside one assembly call
// (shufMulAddList*), each building its tables inline from its coefficient.
//
// ParPar's multi drivers also prefetch the next call's destination during the
// passes (gf16_muladd_multi_stridepf). That needs the address of the next
// destination, which the kernel interface does not carry, so it is not ported.

//go:noescape
func shufMulAddListSSSE3(dst *byte, srcs *srcPtrs, coeffs *coefList, nsrc, n int)

//go:noescape
func shufMulAddListAVX2(dst *byte, srcs *srcPtrs, coeffs *coefList, nsrc, n int)

//go:noescape
func shufMulAddListPfAVX2(dst *byte, srcs *srcPtrs, coeffs *coefList, nsrc, n int)

func mulAddMultiAVX2Pf(dst *byte, srcs *srcPtrs, coeffs *coefList, nsrc, n int) {
	checkPassSize(nsrc)
	if self := selfCoeff(dst, srcs, coeffs, nsrc); self != 0 {
		shufMulAddAVX2(dst, dst, n, self)
	}
	shufMulAddListPfAVX2(dst, srcs, coeffs, nsrc, n)
}

func mulAddMultiSSSE3(dst *byte, srcs *srcPtrs, coeffs *coefList, nsrc, n int) {
	checkPassSize(nsrc)
	if self := selfCoeff(dst, srcs, coeffs, nsrc); self != 0 {
		shufMulAddSSSE3(dst, dst, n, self)
	}
	shufMulAddListSSSE3(dst, srcs, coeffs, nsrc, n)
}

func mulAddMultiAVX2(dst *byte, srcs *srcPtrs, coeffs *coefList, nsrc, n int) {
	checkPassSize(nsrc)
	if self := selfCoeff(dst, srcs, coeffs, nsrc); self != 0 {
		shufMulAddAVX2(dst, dst, n, self)
	}
	shufMulAddListAVX2(dst, srcs, coeffs, nsrc, n)
}

// checkPassSize guards the assembly drivers, which read nsrc entries of the
// source and coefficient arrays.
func checkPassSize(nsrc int) {
	if uint(nsrc) > maxPassRegions {
		panic("gf16: mulAddMulti source count out of range")
	}
}

// selfCoeff combines the coefficients of every source that is dst itself.
// Passes run one after another here, so a source aliasing dst must be
// consumed first and in place (dst ^= self*dst), before other passes change
// it; by linearity a repeated alias just XORs its coefficients.
func selfCoeff(dst *byte, srcs *srcPtrs, coeffs *coefList, nsrc int) (c uint16) {
	for i := 0; i < maxPassRegions && i < nsrc; i++ {
		if srcs[i] == dst {
			c ^= coeffs[i]
		}
	}
	return c
}

func init() {
	cpu := cpuid.CPU
	if !cpu.Supports(cpuid.SSSE3) {
		return // native stays nil: pure-Go path
	}
	ssse3 := &kernel{name: "Shuffle (SSSE3)", stride: shuffleStrideSSSE3, align: 32,
		mul: shufMulSSSE3, mulAdd: shufMulAddSSSE3, mulAddMulti: mulAddMultiSSSE3, xor: xorSSE,
		prepare: shufPrepareSSSE3, finish: shufFinishSSSE3}
	variants := []*kernel{ssse3}
	best := ssse3
	if cpu.Supports(cpuid.AVX2) {
		avx2 := &kernel{name: "Shuffle (AVX2)", stride: shuffleStrideAVX2, align: 64,
			mul: shufMulAVX2, mulAdd: shufMulAddAVX2, mulAddMulti: mulAddMultiAVX2, xor: xorAVX2,
			prepare: shufPrepareAVX2, finish: shufFinishAVX2}
		variants = append(variants, avx2)
		best = avx2
		pf := *avx2
		pf.name, pf.mulAddMulti = "Shuffle (AVX2+pf)", mulAddMultiAVX2Pf
		variants = append(variants, &pf)
	}
	// ParPar prefers Affine(GFNI) over Shuffle wherever both exist.
	for _, k := range affineKernels(&cpu) {
		variants = append(variants, k)
		best = k
	}
	registerKernels(best, variants...)
}
